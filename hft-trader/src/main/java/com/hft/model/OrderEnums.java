package com.hft.model;

/**
 * Перечисления для работы с ордерами. Вынесены в один файл,
 * чтобы не плодить мелкие классы.
 */
public final class OrderEnums {

    private OrderEnums() {}

    /** Сторона сделки. */
    public enum Side {
        BUY, SELL
    }

    /** Тип ордера. */
    public enum Type {
        /** Исполняется немедленно по лучшей доступной цене. Гарантия исполнения,
         *  но не цены — возможно проскальзывание. */
        MARKET,

        /** Исполняется только по указанной цене или лучше. Гарантия цены,
         *  но не исполнения — может висеть в стакане. */
        LIMIT
    }

    /** Time In Force — как долго живёт лимитный ордер. */
    public enum TimeInForce {
        /** Good Till Cancel — висит пока не отменят или не исполнится. */
        GTC,

        /** Immediate Or Cancel — исполнить что можно сразу, остаток отменить.
         *  Допускает частичное исполнение. */
        IOC,

        /** Fill Or Kill — исполнить целиком сразу или отменить полностью.
         *  Частичное исполнение запрещено. */
        FOK
    }
}
